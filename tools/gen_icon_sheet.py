#!/usr/bin/env python3
"""Class emblems and skill icons: the images aion2.app shows, to src/app/src/game_icon_sheet.inc.

Which skill has which icon is the third column of src/game/data/skills.tsv
(tools/gen_skill_table.py fills it in from aion2.app's skill list). This packs the
class emblems and every distinct skill icon into one sheet of 40x40 RGBA slots,
deflated, which the app decodes once and paints into each window's font atlas
(src/app/src/game_icons.cpp). The .inc is committed, so the build never runs Python.

The images are NCSOFT's: the class emblems are the game's party-style ones, the skill
icons the game's own, as aion2.app serves them.

Usage:
  python3 tools/gen_icon_sheet.py --urls          list every image to download, as
                                                  path<TAB>url, path under the folder
  python3 tools/gen_icon_sheet.py --icons DIR     write the .inc from the images in DIR
                                                  (DIR/skills/*.webp, DIR/classes/*.png)
          [--preview sheet.png]                   and a contact sheet to look them over
  python3 tools/gen_icon_sheet.py --check         fail if the .inc's index no longer
                                                  matches the TSV (make test)

Download what --urls lists yourself (see .claude/skills/after-game-patch): this script
never touches the network. Building needs Pillow with WebP; --check and --urls do not.
"""
import argparse
import colorsys
import os
import re
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "src", "game", "data", "skills.tsv")
INC = os.path.join(ROOT, "src", "app", "src", "game_icon_sheet.inc")

SITE = "https://aion2.app"
PX = 40

# game::AionClass in order, with the file aion2.app names its party-style emblem by.
# Unknown and Brawler have none: the Brawler is not on Global, and its emblem is
# not in the party style.
CLASSES = [
    ("Unknown", None),
    ("Gladiator", "gladiator"),
    ("Templar", "templar"),
    ("Assassin", "assassin"),
    ("Ranger", "ranger"),
    ("Sorcerer", "sorcerer"),
    ("Elementalist", "spiritmaster"),
    ("Cleric", "cleric"),
    ("Chanter", "chanter"),
    ("Brawler", None),
]

ICON = re.compile(r"ICON_\w+")
PIXELS_MARKER = "// Pixels:"
UNSERVED = "// Not served by aion2.app, so without an icon:"


def read_icons(path):
    """{code: icon} for every skill the TSV gives an icon."""
    icons = {}
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) == 3 and parts[2]:
                if not ICON.fullmatch(parts[2]):
                    sys.exit(f"{path}:{n}: icon {parts[2]!r} is not an ICON_ name")
                icons[int(parts[0])] = parts[2]
    return icons


def layout(icons, unserved=()):
    """The slots in order, as (kind, name): the emblems first, then each distinct
    skill icon by name, less those the site does not serve. The index depends on
    the TSV and that list alone, so --check needs no images."""
    slots = [("class", file) for _, file in CLASSES if file]
    slots += [("skill", name) for name in sorted(set(icons.values()) - set(unserved))]
    return slots


def render_index(icons, unserved=()):
    slots = layout(icons, unserved)
    slot_of = {s: i for i, s in enumerate(slots)}
    class_slots = [str(slot_of[("class", file)]) if file else "-1" for _, file in CLASSES]
    lines = [
        "// Generated by tools/gen_icon_sheet.py from src/game/data/skills.tsv and the",
        "// images aion2.app serves. Do not edit: download them again and run the script.",
        "// The class emblems and skill icons are NCSOFT's, outside this project's licence.",
    ]
    # The site's skill list names some icons it answers with a page, not an image.
    lines += [f"{UNSERVED} {name}" for name in sorted(unserved)]
    lines += [
        f"constexpr int kIconPx = {PX};",
        f"constexpr int kIconSlots = {len(slots)};",
        "/// Each class's emblem, by game::AionClass; -1 for none.",
        f"constexpr int16_t kClassSlots[] = {{{', '.join(class_slots)}}};",
        "/// {skill code, slot}, sorted by code for a binary search.",
        "constexpr SkillIconRow kSkillIcons[] = {",
    ]
    lines += [f"{{{code}u, {slot_of[('skill', icon)]}}},"
              for code, icon in sorted(icons.items()) if ("skill", icon) in slot_of]
    lines.append("};")
    return "\n".join(lines) + "\n"


def urls(icons):
    for kind, name in layout(icons):
        if kind == "class":
            print(f"classes/{name}.png\t{SITE}/class-icons/{name}.png")
        else:
            print(f"skills/{name}.webp\t{SITE}/db-item-icons/{name}.webp")


def fit(img):
    """`img` scaled into PX x PX, aspect kept, centred on transparency. Resized
    premultiplied, so transparent pixels lend no colour to the edges."""
    from PIL import Image

    img = img.convert("RGBA").convert("RGBa")
    scale = PX / max(img.width, img.height)
    w = max(1, round(img.width * scale))
    h = max(1, round(img.height * scale))
    img = img.resize((w, h), Image.LANCZOS).convert("RGBA")
    out = Image.new("RGBA", (PX, PX), (0, 0, 0, 0))
    out.paste(img, ((PX - w) // 2, (PX - h) // 2))
    return out


def bright_tone(img):
    """The emblem's colour as it reads on a dark background: the mean of its
    brightest saturated pixels."""
    picked = []
    data = img.tobytes()
    for i in range(0, len(data), 4):
        r, g, b, a = data[i:i + 4]
        if a < 200:
            continue
        _, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
        if s > 0.30 and v > 0.35:
            picked.append((v, (r, g, b)))
    if not picked:
        return None
    picked.sort()
    top = [c for _, c in picked[int(len(picked) * 0.80):]]
    return "#" + "".join(f"{sum(c[k] for c in top) // len(top):02X}" for k in range(3))


def build(folder, preview):
    from PIL import Image, UnidentifiedImageError

    icons = read_icons(TSV)
    images = []
    missing = []
    unserved = []
    for kind, name in layout(icons):
        path = os.path.join(folder, "classes" if kind == "class" else "skills",
                            f"{name}.png" if kind == "class" else f"{name}.webp")
        if not os.path.exists(path):
            missing.append(path)
            continue
        try:
            images.append(fit(Image.open(path)))
        except UnidentifiedImageError:
            # A page where the image should be: the site lists an icon it lacks.
            if kind == "class":
                sys.exit(f"{path} is not an image")
            unserved.append(name)
    if missing:
        sys.exit(f"{len(missing)} images missing, such as {missing[0]}: download what --urls lists")
    if unserved:
        print(f"{len(unserved)} icons are not served (their skills get none): {', '.join(unserved)}")
    slots = layout(icons, unserved)

    for (cls, file), img in zip([c for c in CLASSES if c[1]], images):
        print(f"{cls:<13} {bright_tone(img)}")

    raw = b"".join(img.tobytes() for img in images)
    packer = zlib.compressobj(9, zlib.DEFLATED, -15)  # raw DEFLATE, as archive::inflate reads
    packed = packer.compress(raw) + packer.flush()

    lines = [render_index(icons, unserved).rstrip("\n")]
    lines.append(f"{PIXELS_MARKER} every slot's {PX}x{PX} RGBA (straight alpha), slot after slot,")
    lines.append("// as one raw DEFLATE stream.")
    lines.append(f"constexpr size_t kIconPixelsSize = {len(raw)};")
    lines.append("const uint8_t kIconPixelsDeflated[] = {")
    for i in range(0, len(packed), 32):
        lines.append(",".join(str(b) for b in packed[i:i + 32]) + ",")
    lines.append("};")
    with open(INC, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(slots)} icons to {os.path.relpath(INC, ROOT)}: "
          f"{len(raw)} bytes, {len(packed)} deflated")

    if preview:
        per_row = 20
        rows = (len(images) + per_row - 1) // per_row
        sheet = Image.new("RGBA", (per_row * (PX + 4) + 4, rows * (PX + 4) + 4), (16, 18, 26, 255))
        for i, img in enumerate(images):
            sheet.alpha_composite(img, (4 + (i % per_row) * (PX + 4), 4 + (i // per_row) * (PX + 4)))
        sheet.save(preview)
        print(f"wrote {preview}")


def check():
    with open(INC, encoding="utf-8") as f:
        text = f.read()
    index = text.split(PIXELS_MARKER, 1)[0]
    unserved = [line[len(UNSERVED):].strip() for line in index.splitlines() if line.startswith(UNSERVED)]
    if index != render_index(read_icons(TSV), unserved):
        sys.exit("game_icon_sheet.inc does not match skills.tsv's icons: download the icons "
                 "(python3 tools/gen_icon_sheet.py --urls) and run it with --icons")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--urls", action="store_true")
    ap.add_argument("--icons", metavar="DIR")
    ap.add_argument("--preview", metavar="PNG")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.urls:
        urls(read_icons(TSV))
    elif args.icons:
        build(args.icons, args.preview)
    elif args.check:
        check()
    else:
        ap.print_help()


if __name__ == "__main__":
    main()
