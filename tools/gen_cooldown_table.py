#!/usr/bin/env python3
"""Skill cooldowns: plugins/auras/data/cooldowns.tsv to plugins/auras/src/cooldown_table.inc.

The TSV is the source of truth: one `code<TAB>kind<TAB>cooldown_ms<TAB>cuts<TAB>uses`
per line, `#` for comments. The .inc is generated from it and committed, so the build never
runs Python.

  kind         A: an active skill, whose specialties are picked, one per slot; the
               variant digits of the code it is cast with name them (12350130:
               specialties 1 and 3). S: a stigma, which keeps every specialty it
               unlocked; the code's tens digit counts them (18190041: four).
  cooldown_ms  the cooldown aion2.app lists, the same at every level.
  cuts         the specialties that shorten the skill's own cooldown, as
               index:ms pairs, comma separated (1:5000 for "-5s cooldown"), or -.
  uses         the specialties that let it be used again before its cooldown, as
               index:count pairs (1:1 for "+1 consecutive use"), or -.

Usage:
  python3 tools/gen_cooldown_table.py            write cooldown_table.inc from the TSV
  python3 tools/gen_cooldown_table.py --check    fail if the .inc is out of date (make test)
  python3 tools/gen_cooldown_table.py --import-pages DIR
                                            rebuild the TSV from aion2.app's skill
                                            pages saved in DIR (<code>.html)

The import reads pages you downloaded yourself (see .claude/skills/after-game-patch):
this script never touches the network.
"""
import argparse
import datetime
import glob
import html
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "plugins", "auras", "data", "cooldowns.tsv")
INC = os.path.join(ROOT, "plugins", "auras", "src", "cooldown_table.inc")

# Specialty slots per skill: the most a page has shown is five.
MAX_SPECIALTIES = 5
# The hint each page draws over its specialties tells the kinds apart. Both texts
# also sit in every page's embedded data, so only the drawn element counts.
ACTIVE_HINT = ">Unlocked as the skill levels"
STIGMA_HINT = ">A stigma keeps every specialty"
CANONICAL = re.compile(r'<link rel="canonical" href="https://aion2\.app/db/skills/(\d+)"')
# The cooldown at level 1, in seconds, from the page's embedded level table.
COOLDOWN = re.compile(r'\\"level\\":1,\\"cooldown\\":([\d.]+|null)')
# One specialty row: its level badge, then its text (spans and links inside).
SPECIALTY = re.compile(r'Level<!-- --> <!-- -->(\d+)</span><span class="text-sm[^"]*">(.*?)</span></div>', re.S)
# A cut to the skill's own cooldown. "-2s [Warding Strike] cooldown on hit" cuts
# another skill's, which the server reports itself (47 38).
OWN_CUT = re.compile(r"^-(\d+(?:\.\d+)?)s cooldown$")
# More uses before the cooldown: charges.
MORE_USES = re.compile(r"^\+(\d+) consecutive uses?$")


def parse_pairs(text, n):
    """`index:value,...` or -, as {index: value}."""
    if text == "-":
        return {}
    pairs = {}
    for part in text.split(","):
        index, _, value = part.partition(":")
        if not index.isdigit() or not value.isdigit() or not 1 <= int(index) <= MAX_SPECIALTIES:
            sys.exit(f"{TSV}:{n}: bad pair {part!r}: expected index:value")
        pairs[int(index)] = int(value)
    return pairs


def format_pairs(pairs):
    return ",".join(f"{i}:{v}" for i, v in sorted(pairs.items())) or "-"


def read_tsv(path):
    rows = {}
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) != 5 or not parts[0].isdigit() or parts[1] not in ("A", "S") or not parts[2].isdigit():
                sys.exit(f"{path}:{n}: expected code<TAB>A|S<TAB>cooldown_ms<TAB>cuts<TAB>uses")
            code = int(parts[0])
            if code in rows:
                sys.exit(f"{path}:{n}: code {code} listed twice")
            rows[code] = (parts[1], int(parts[2]), parse_pairs(parts[3], n), parse_pairs(parts[4], n))
    return rows


def render_inc(rows):
    lines = [
        "// Generated by tools/gen_cooldown_table.py from plugins/auras/data/cooldowns.tsv.",
        "// Do not edit: change the TSV and run the script.",
        "// {code, stigma, cooldown_ms, {cut_ms of specialty 1..5}, {extra uses of 1..5}}, sorted by code.",
    ]
    for code, (kind, ms, cuts, uses) in sorted(rows.items()):
        cut = ", ".join(f"{cuts.get(i, 0)}u" for i in range(1, MAX_SPECIALTIES + 1))
        more = ", ".join(f"{uses.get(i, 0)}u" for i in range(1, MAX_SPECIALTIES + 1))
        lines.append(f"{{{code}u, {'true' if kind == 'S' else 'false'}, {ms}u, {{{cut}}}, {{{more}}}}},")
    return "\n".join(lines) + "\n"


def page_row(text):
    """(code, kind, cooldown_ms, cuts, uses) of one saved page, or None for a skill with no cooldown."""
    canonical = CANONICAL.search(text)
    cooldown = COOLDOWN.search(text)
    if canonical is None or cooldown is None or cooldown.group(1) == "null":
        return None
    ms = round(float(cooldown.group(1)) * 1000)
    if ms <= 0:
        return None
    active = text.find(ACTIVE_HINT)
    stigma = text.find(STIGMA_HINT)
    start = max(active, stigma)
    kind = "S" if stigma >= 0 and stigma == start else "A"
    cuts = {}
    uses = {}
    if start >= 0:
        end = text.find(">Details<", start)
        section = text[start:end if end > start else len(text)]
        for index, m in enumerate(SPECIALTY.finditer(section), 1):
            if index > MAX_SPECIALTIES:
                break
            words = html.unescape(" ".join(re.sub(r"<[^>]+>", "", m.group(2)).split()))
            cut = OWN_CUT.match(words)
            if cut:
                cuts[index] = round(float(cut.group(1)) * 1000)
            more = MORE_USES.match(words)
            if more:
                uses[index] = int(more.group(1))
    return int(canonical.group(1)), kind, ms, cuts, uses


def import_pages(folder):
    rows = {}
    pages = sorted(glob.glob(os.path.join(folder, "*.html")))
    if not pages:
        sys.exit(f"no *.html in {folder}")
    for page in pages:
        with open(page, encoding="utf-8") as f:
            row = page_row(f.read())
        if row is not None:
            rows[row[0]] = row[1:]
    today = datetime.date.today().isoformat()
    with open(TSV, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            "# AION 2 skill cooldowns, for the aura overlay's estimates (plugins/auras/AGENTS.md).\n"
            "# code<TAB>kind<TAB>cooldown_ms<TAB>cuts<TAB>uses, one row per skill with a cooldown.\n"
            "# kind: A, an active skill whose specialties are picked (the cast code's variant\n"
            "# digits name them); S, a stigma, which keeps all it unlocked (the tens digit\n"
            "# counts them). cuts: the specialties that shorten the skill's own cooldown, as\n"
            "# index:ms in the page's order; - for none. uses: the ones that allow more uses\n"
            "# before the cooldown (\"+1 consecutive use\"), as index:count.\n"
            "#\n"
            f"# Source: aion2.app's skill pages (aion2.app/db/skills/<code>), retrieved {today}.\n"
            "# Regenerate with tools/gen_cooldown_table.py.\n"
        )
        for code, (kind, ms, cuts, uses) in sorted(rows.items()):
            f.write(f"{code}\t{kind}\t{ms}\t{format_pairs(cuts)}\t{format_pairs(uses)}\n")
    print(f"wrote {len(rows)} cooldowns to {os.path.relpath(TSV, ROOT)}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--import-pages", metavar="DIR")
    args = ap.parse_args()
    if args.import_pages:
        import_pages(args.import_pages)
    text = render_inc(read_tsv(TSV))
    if args.check:
        with open(INC, encoding="utf-8") as f:
            if f.read() != text:
                sys.exit("cooldown_table.inc is out of date: run python3 tools/gen_cooldown_table.py")
        return
    with open(INC, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(INC, ROOT)}")


if __name__ == "__main__":
    main()
