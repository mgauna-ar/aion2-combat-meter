#!/usr/bin/env python3
"""Effect names: src/game/data/effects.tsv to src/game/src/effect_table.inc.

The TSV is the source of truth: one `effect id<TAB>name<TAB>kind[<TAB>icon]` per line,
`#` for comments. The id is the one 2a 38 carries; the kind says what puts the effect
on: `skill` (a class skill), `item` (a scroll, food, a potion) or `other`. The icon,
on an item's effect, names the item's icon, which tools/gen_icon_sheet.py packs for
the app; the .inc here holds the names and kinds only. It is generated from the TSV
and committed, so the build never runs Python.

Usage:
  python3 tools/gen_effect_table.py            write effect_table.inc from the TSV
  python3 tools/gen_effect_table.py --check    fail if the .inc is out of date (make test)
  python3 tools/gen_effect_table.py --import-pages DIR
                                            rebuild the TSV from questlog.gg's
                                            status-effect list pages saved in DIR
                                            (*.json)

The import reads pages you downloaded yourself (see .claude/skills/after-game-patch):
this script never touches the network.
"""
import argparse
import datetime
import glob
import json
import re
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "src", "game", "data", "effects.tsv")
INC = os.path.join(ROOT, "src", "game", "src", "effect_table.inc")

ICON = re.compile(r"\w+")
KINDS = {"skill": "Skill", "item": "Item", "other": "Unknown"}


def read_tsv(path):
    """{id: (name, kind, icon)}, the icon "" for an effect without one."""
    rows = {}
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) not in (3, 4) or not parts[0].isdigit() or not parts[1] or parts[2] not in KINDS:
                sys.exit(f"{path}:{n}: expected id<TAB>name<TAB>{'|'.join(KINDS)}[<TAB>icon]")
            icon = parts[3] if len(parts) == 4 else ""
            if icon and not ICON.fullmatch(icon):
                sys.exit(f"{path}:{n}: icon {icon!r} is not an icon's name")
            code = int(parts[0])
            if not 0 < code <= 0xFFFFFFFF:
                sys.exit(f"{path}:{n}: id {code} does not fit a u32")
            if code in rows:
                sys.exit(f"{path}:{n}: id {code} listed twice")
            rows[code] = (parts[1], parts[2], icon)
    return rows


def c_string(s):
    out = []
    for b in s.encode("utf-8"):
        ch = chr(b)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= b < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\{b:03o}")  # octal: never swallows the next character
    return '"' + "".join(out) + '"'


def render_inc(rows):
    lines = [
        "// Generated by tools/gen_effect_table.py from src/game/data/effects.tsv.",
        "// Do not edit: change the TSV and run the script.",
        "// {effect id, name, kind}, sorted by id for a binary search.",
    ]
    lines += [f"{{{code}u, {c_string(name)}, EffectKind::{KINDS[kind]}}}," for code, (name, kind, _) in sorted(rows.items())]
    return "\n".join(lines) + "\n"


def kind_of(code, icon):
    """What puts an effect on, from what the list says of it: an item's icon is an
    item's effect; a class skill's effect is its code times ten plus a digit."""
    if "/Texture/Item/" in icon:
        return "item"
    if 10_000_000 <= code // 10 <= 19_999_999:
        return "skill"
    return "other"


def import_pages(folder):
    rows = {}
    pages = sorted(glob.glob(os.path.join(folder, "*.json")))
    if not pages:
        sys.exit(f"no *.json in {folder}")
    for page in pages:
        with open(page, encoding="utf-8") as f:
            try:
                entries = json.load(f)["result"]["data"]["pageData"]
            except (ValueError, KeyError, TypeError):
                sys.exit(f"{page}: not a status-effect list page")
        for e in entries:
            code = str(e.get("id", ""))
            name = " ".join(str(e.get("name") or "").split())
            if not code.isdigit() or not 0 < int(code) <= 0xFFFFFFFF or not name or e.get("isDisabled"):
                continue
            kind = kind_of(int(code), str(e.get("icon") or ""))
            # ".../Item/ETC/Icon_Item_X.Icon_Item_X": the asset's own name is the icon's.
            icon = str(e.get("icon") or "").rsplit(".", 1)[-1] if kind == "item" else ""
            rows[int(code)] = (name, kind, icon if ICON.fullmatch(icon) else "")
    if not rows:
        sys.exit(f"no effects in {folder}")
    today = datetime.date.today().isoformat()
    with open(TSV, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            "# AION 2 effect names by effect id, as an effect put on (2a 38) carries it.\n"
            "# The third column says what puts it on: skill (a class skill), item (a\n"
            "# scroll, food, a potion) or other (a monster, a zone, the system). An effect\n"
            "# not listed takes the name of the skill behind it (game::effect_name). The\n"
            "# fourth column, on an item's effect, names the item's icon, which\n"
            "# tools/gen_icon_sheet.py packs for the app.\n"
            "#\n"
            "# Source: questlog.gg's status-effect database\n"
            f"# (questlog.gg/aion-2/en/db/status-effects), retrieved {today}. English names as\n"
            "# the site lists them. Regenerate with tools/gen_effect_table.py.\n"
        )
        for code, (name, kind, icon) in sorted(rows.items()):
            f.write(f"{code}\t{name}\t{kind}\t{icon}\n" if icon else f"{code}\t{name}\t{kind}\n")
    by_kind = {}
    for _, kind, _ in rows.values():
        by_kind[kind] = by_kind.get(kind, 0) + 1
    print(f"wrote {len(rows)} effects to {os.path.relpath(TSV, ROOT)}: " +
          ", ".join(f"{n} {k}" for k, n in sorted(by_kind.items())))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--import-pages", metavar="DIR")
    args = ap.parse_args()
    if args.import_pages:
        import_pages(args.import_pages)
    text = render_inc(read_tsv(TSV))
    if args.check:
        with open(INC, encoding="utf-8") as f:
            if f.read() != text:
                sys.exit("effect_table.inc is out of date: run python3 tools/gen_effect_table.py")
        return
    with open(INC, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(INC, ROOT)}")


if __name__ == "__main__":
    main()
