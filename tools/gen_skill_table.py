#!/usr/bin/env python3
"""Skill names: src/meter/data/skills.tsv to src/meter/src/skill_table.inc.

The TSV is the source of truth: one `code<TAB>name` per line, `#` for comments.
The .inc is generated from it and committed, so the build never runs Python.

Usage:
  python3 tools/gen_skill_table.py            write skill_table.inc from the TSV
  python3 tools/gen_skill_table.py --check    fail if the .inc is out of date (make test)
  python3 tools/gen_skill_table.py --import-pages DIR
                                            rebuild the TSV from aion2.app's skill
                                            list pages saved in DIR (page1.html, ...)

The import reads pages you downloaded yourself (see .claude/skills/after-game-patch):
this script never touches the network.
"""
import argparse
import datetime
import glob
import html
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "src", "meter", "data", "skills.tsv")
INC = os.path.join(ROOT, "src", "meter", "src", "skill_table.inc")

# Text a page shows in place of a name for entries that have none.
PLACEHOLDERS = {
    "Active", "Passive", "Stigma", "System",
    "Gladiator", "Templar", "Assassin", "Ranger", "Sorcerer", "Elementalist",
    "Cleric", "Chanter", "Brawler", "Fighter",
}


def read_tsv(path):
    rows = {}
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) != 2 or not parts[0].isdigit() or not parts[1]:
                sys.exit(f"{path}:{n}: expected code<TAB>name")
            code = int(parts[0])
            if code in rows:
                sys.exit(f"{path}:{n}: code {code} listed twice")
            rows[code] = parts[1]
    return rows


def c_string(s):
    out = []
    for b in s.encode("utf-8"):
        ch = chr(b)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= b < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\{b:03o}")  # octal: never swallows the next character
    return '"' + "".join(out) + '"'


def render_inc(rows):
    lines = [
        "// Generated by tools/gen_skill_table.py from src/meter/data/skills.tsv.",
        "// Do not edit: change the TSV and run the script.",
        "// {code, name}, sorted by code for a binary search.",
    ]
    lines += [f"{{{code}u, {c_string(name)}}}," for code, name in sorted(rows.items())]
    return "\n".join(lines) + "\n"


def import_pages(folder):
    rows = {}
    pages = sorted(glob.glob(os.path.join(folder, "page*.html")))
    if not pages:
        sys.exit(f"no page*.html in {folder}")
    for page in pages:
        with open(page, encoding="utf-8") as f:
            s = f.read()
        for m in re.finditer(r'href="/db/skills/(\d+)"[^>]*>(.*?)</a>', s, re.S):
            parts = [html.unescape(" ".join(p.split())) for p in re.split(r"<[^>]+>", m.group(2))]
            parts = [p for p in parts if p]
            if parts and parts[0] not in PLACEHOLDERS:
                rows[int(m.group(1))] = parts[0]
    today = datetime.date.today().isoformat()
    with open(TSV, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            "# AION 2 skill names by skill code, as damage (04 38) and tick (05 38) records\n"
            "# carry them. A code is 8 digits: the first two are the class (11 Gladiator to\n"
            "# 18 Chanter, 19 Brawler), code / 10000 is the skill, and the low four digits a\n"
            "# variant. A variant without a row of its own takes its skill's name.\n"
            "#\n"
            f"# Source: aion2.app's skill database (aion2.app/db/skills), retrieved {today};\n"
            "# the site says its data comes from NCSOFT's official AION 2 API. English\n"
            "# names as the site lists them. Regenerate with tools/gen_skill_table.py.\n"
        )
        for code, name in sorted(rows.items()):
            f.write(f"{code}\t{name}\n")
    print(f"wrote {len(rows)} skills to {os.path.relpath(TSV, ROOT)}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--import-pages", metavar="DIR")
    args = ap.parse_args()
    if args.import_pages:
        import_pages(args.import_pages)
    text = render_inc(read_tsv(TSV))
    if args.check:
        with open(INC, encoding="utf-8") as f:
            if f.read() != text:
                sys.exit("skill_table.inc is out of date: run python3 tools/gen_skill_table.py")
        return
    with open(INC, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(INC, ROOT)}")


if __name__ == "__main__":
    main()
