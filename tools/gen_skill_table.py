#!/usr/bin/env python3
"""Skill names: src/game/data/skills.tsv to src/game/src/skill_table.inc.

The TSV is the source of truth: one `code<TAB>name[<TAB>icon]` per line, `#` for
comments. The icon is the game's name for the skill's icon (ICON_AS_SKILL_001; for a
Theostone's hit, its item's), which tools/gen_icon_sheet.py packs for the app; the
.inc here holds the names only. It
is generated from the TSV and committed, so the build never runs Python.

Usage:
  python3 tools/gen_skill_table.py            write skill_table.inc from the TSV
  python3 tools/gen_skill_table.py --check    fail if the .inc is out of date (make test)
  python3 tools/gen_skill_table.py --import-pages DIR
                                            rebuild the TSV from questlog.gg's skill
                                            list pages saved in DIR (*.json), and
                                            aion2.app's (page1.html, ...) for the
                                            skills questlog.gg does not list

questlog.gg's list is the source: aion2.app's has lost names (the Brawler's, 2026-11).
aion2.app's still gives the skills questlog.gg's leaves out: Dodge, each class's
weapon, the Elementalist's spirits, and skills no class's tree shows.

The import rewrites the rows above the TSV's "# By hand" line and keeps that line and
everything after it. It reads pages you downloaded yourself (see
.claude/skills/after-game-patch): this script never touches the network.
"""
import argparse
import datetime
import glob
import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "src", "game", "data", "skills.tsv")
INC = os.path.join(ROOT, "src", "game", "src", "skill_table.inc")

# Text a page shows in place of a name for entries that have none.
PLACEHOLDERS = {
    "Active", "Passive", "Stigma", "System",
    "Gladiator", "Templar", "Assassin", "Ranger", "Sorcerer", "Elementalist",
    "Cleric", "Chanter", "Brawler", "Fighter",
}


# A skill's icon (ICON_GL_SKILL_003), or an item's (Icon_Item_Usable_Godstone_WP_r_011).
ICON = re.compile(r"(?:ICON|Icon)_\w+")

HAND_MARKER = "# By hand"
HAND_SECTION = HAND_MARKER + ": codes no skill list carries. --import-pages keeps this section as it is.\n"


def read_rows(path):
    """{code: (name, icon)}, the icon "" for a skill without one."""
    rows = {}
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) not in (2, 3) or not parts[0].isdigit() or not parts[1]:
                sys.exit(f"{path}:{n}: expected code<TAB>name[<TAB>icon]")
            icon = parts[2] if len(parts) == 3 else ""
            if icon and not ICON.fullmatch(icon):
                sys.exit(f"{path}:{n}: icon {icon!r} is not an icon's name")
            code = int(parts[0])
            if code in rows:
                sys.exit(f"{path}:{n}: code {code} listed twice")
            rows[code] = (parts[1], icon)
    return rows


def read_tsv(path):
    return {code: name for code, (name, _) in read_rows(path).items()}


def c_string(s):
    out = []
    for b in s.encode("utf-8"):
        ch = chr(b)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= b < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\{b:03o}")  # octal: never swallows the next character
    return '"' + "".join(out) + '"'


def hand_section(path):
    """The TSV from its "# By hand" line on, which the import keeps as it is."""
    if not os.path.exists(path):
        return HAND_SECTION
    with open(path, encoding="utf-8") as f:
        lines = f.readlines()
    for i, line in enumerate(lines):
        if line.startswith(HAND_MARKER):
            return "".join(lines[i:])
    return HAND_SECTION


def codes_by_hand(path):
    """The codes in the TSV's "# By hand" section, which the import leaves alone."""
    return {int(line.split("\t")[0]) for line in hand_section(path).splitlines() if line[:1].isdigit()}


def render_inc(rows):
    lines = [
        "// Generated by tools/gen_skill_table.py from src/game/data/skills.tsv.",
        "// Do not edit: change the TSV and run the script.",
        "// {code, name}, sorted by code for a binary search.",
    ]
    lines += [f"{{{code}u, {c_string(name)}}}," for code, name in sorted(rows.items())]
    return "\n".join(lines) + "\n"


def read_questlog(folder):
    """{code: (name, icon)} from questlog.gg's skill list pages (*.json)."""
    rows = {}
    for page in sorted(glob.glob(os.path.join(folder, "*.json"))):
        with open(page, encoding="utf-8") as f:
            try:
                entries = json.load(f)["result"]["data"]["pageData"]
            except (ValueError, KeyError, TypeError):
                sys.exit(f"{page}: not a questlog.gg skill list page")
        for e in entries:
            code, name = str(e.get("id", "")), " ".join(str(e.get("name", "")).split())
            if not code.isdigit() or not name:
                continue
            # ".../Skill/ICON_GT_SKILL_001.ICON_GT_SKILL_001"
            icon = str(e.get("icon", "")).rsplit(".", 1)[-1]
            rows[int(code)] = (name, icon if ICON.fullmatch(icon) else "")
    return rows


def import_pages(folder):
    rows = read_questlog(folder)
    if not rows:
        sys.exit(f"no questlog.gg skill list pages (*.json) in {folder}")
    from_questlog = len(rows)
    # Skills aion2.app's pages list without an English name (the Brawler's, since
    # 2026-11): failing questlog.gg, a name already in the TSV stays.
    unnamed = {}
    pages = sorted(glob.glob(os.path.join(folder, "page*.html")))
    if not pages:
        sys.exit(f"no aion2.app skill list pages (page*.html) in {folder}")
    for page in pages:
        with open(page, encoding="utf-8") as f:
            s = f.read()
        for m in re.finditer(r'href="/db/skills/(\d+)"[^>]*>(.*?)</a>', s, re.S):
            code = int(m.group(1))
            parts = [html.unescape(" ".join(p.split())) for p in re.split(r"<[^>]+>", m.group(2))]
            parts = [p for p in parts if p]
            icon = re.search(r'/db-item-icons/(ICON_\w+)\.webp', m.group(2))
            icon = icon.group(1) if icon else ""
            if code in rows:
                # questlog.gg gives no icon for the common block's (Glide, Flight).
                if not rows[code][1] and icon:
                    rows[code] = (rows[code][0], icon)
            elif parts and parts[0] not in PLACEHOLDERS:
                rows[code] = (parts[0], icon)
            else:
                unnamed[code] = icon
    print(f"{from_questlog} skills from questlog.gg, {len(rows) - from_questlog} more from aion2.app's pages")
    hand_codes = codes_by_hand(TSV)
    for code in hand_codes & rows.keys():
        print(f"skill {code} is in the TSV's \"# By hand\" section; kept that row", file=sys.stderr)
    rows = {code: row for code, row in rows.items() if code not in hand_codes}
    kept = 0
    if os.path.exists(TSV):
        for code, (name, _) in read_rows(TSV).items():
            if code in unnamed and code not in rows and code not in hand_codes:
                rows[code] = (name, unnamed[code])
                kept += 1
    if kept:
        print(f"kept the TSV's name for {kept} skills neither site names")
    today = datetime.date.today().isoformat()
    hand = hand_section(TSV)  # read before the TSV is truncated below
    with open(TSV, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            "# AION 2 skill names by skill code, as damage (04 38) and tick (05 38) records\n"
            "# carry them. A code is 8 digits: the first two are the class (11 Gladiator to\n"
            "# 18 Chanter, 19 Brawler), code / 10000 is the skill, and the low four digits a\n"
            "# variant. In each class's common block (XX00xxxx), its weapon and Dodge, the\n"
            "# skill is code / 100. A variant without a row of its own takes its skill's\n"
            "# name. The third column, when there is one, names the skill's icon, which\n"
            "# tools/gen_icon_sheet.py packs for the app.\n"
            "#\n"
            f"# Sources, retrieved {today}: questlog.gg's skill database\n"
            "# (questlog.gg/aion-2/en/db/skills), English names as it lists them; and\n"
            "# aion2.app's (aion2.app/db/skills) for the skills questlog.gg does not list\n"
            "# (Dodge, the weapons, the Elementalist's spirits), which the site says it\n"
            "# reads from NCSOFT's official AION 2 API.\n"
            "# Regenerate with tools/gen_skill_table.py.\n"
        )
        for code, (name, icon) in sorted(rows.items()):
            f.write(f"{code}\t{name}\t{icon}\n" if icon else f"{code}\t{name}\n")
        f.write("\n" + hand)
    print(f"wrote {len(rows)} skills to {os.path.relpath(TSV, ROOT)}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--import-pages", metavar="DIR")
    args = ap.parse_args()
    if args.import_pages:
        import_pages(args.import_pages)
    text = render_inc(read_tsv(TSV))
    if args.check:
        with open(INC, encoding="utf-8") as f:
            if f.read() != text:
                sys.exit("skill_table.inc is out of date: run python3 tools/gen_skill_table.py")
        return
    with open(INC, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(INC, ROOT)}")


if __name__ == "__main__":
    main()
